// Writes supabase/seed.sql from the films in src/components/aqua/videos.ts.
// Run with: npm run seed:sql
import { writeFileSync } from "node:fs";
import { VIDEOS } from "../src/components/aqua/videos.ts";

function sql(value: string | number | boolean | undefined | null): string {
  if (value === undefined || value === null) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return `'${value.replaceAll("'", "''")}'`;
}

const columns =
  "id, visible, sort_order, title, genre, description, studio, duration, width, height, license, src, src_hd, src_4k, poster, poster_width, poster_height, poster_credit, still, source_page";

const rows = VIDEOS.map((v, index) =>
  [
    v.id,
    true,
    (index + 1) * 10,
    v.title,
    v.genre,
    v.description,
    v.studio,
    v.duration,
    v.width,
    v.height,
    v.license,
    v.src,
    v.srcHd,
    v.src4k,
    v.poster,
    v.posterWidth,
    v.posterHeight,
    v.posterCredit,
    v.still,
    v.sourcePage,
  ]
    .map(sql)
    .join(", "),
);

const out = `-- Generated by scripts/generate-seed.ts from src/components/aqua/videos.ts.
-- Run after schema.sql. Re-running it resets these films to the values below.

insert into public.videos (${columns}) values
${rows.map((row) => `  (${row})`).join(",\n")}
on conflict (id) do update set
${columns
  .split(", ")
  .filter((c) => c !== "id")
  .map((c) => `  ${c} = excluded.${c}`)
  .join(",\n")};

insert into public.site_settings (id, tagline, promo_title_line1, promo_title_line2, promo_text)
values (1, '好看的短片 · 一划就有', '', '', '共 {count} 部高清影片，来自 Blender 工作室和 NASA，全部免费观看，像刷短视频一样一部接一部。')
on conflict (id) do nothing;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out);
console.log(`Wrote supabase/seed.sql with ${VIDEOS.length} films.`);
